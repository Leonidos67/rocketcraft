const pluralDirections = (count: number) => {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod100 >= 11 && mod100 <= 14) return `${count} направлений`;
  if (mod10 === 1) return `${count} направление`;
  if (mod10 >= 2 && mod10 <= 4) return `${count} направления`;
  return `${count} направлений`;
};

export const getServicesHeroTitle = () => {
  const label = pluralDirections(servicesCatalog.length);
  return `${label.charAt(0).toUpperCase() + label.slice(1)} — одна система для роста бизнеса`;
};

export const getServicesHeroIntro = () => {
  const preview = servicesCatalog
    .slice(0, 4)
    .map((c) => c.title.toLowerCase())
    .join(', ');
  return `${preview} и другие. ${servicesCatalog.length} направлений digital-услуг — одна связанная экосистема под ваш бизнес.`;
};

export const getCategoryById = (id: string) =>
  servicesCatalog.find((c) => c.id === id);

export const getServiceById = (categoryId: string, serviceId: string) => {
  const category = getCategoryById(categoryId);
  return category?.services.find((s) => s.id === serviceId);
};

export const formatPrice = (amount: number) =>
  `от ${amount.toLocaleString('ru-RU')} ₽`;

export const getDiscountPercent = (priceFrom: number, priceOld?: number) => {
  if (!priceOld || priceOld <= priceFrom) return null;
  return Math.round(((priceOld - priceFrom) / priceOld) * 100);
};
